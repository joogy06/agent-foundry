def test_migrate_proposes_and_archives_without_overwrite(tmp_path: Path) -> None:
    project = tmp_path
    (project / "PROJECT.md").write_text(
        "# Project\n## Changelog\n- did x\n## Why\nbecause\n## Components\n| a | b |\n")
    result = migrate_mod.migrate(project, partition_doc=_GOOD_PARTITION,
                                 intent_manifest={"summary": {"failed": 0, "gap": 0}},
                                 apply=False)
    assert result["status"] == "proposed"
    # original archived byte-for-byte
    assert result["archived_count"] == 1
    manifest = json.loads(Path(result["manifest"]).read_text())
    assert manifest["applied"] is False
    # the real PROJECT.md is UNTOUCHED (shadow-first; no overwrite without approval)
    assert (project / "PROJECT.md").read_text().startswith("# Project")
    # proposal classifies sections into buckets
    headers = {s["header"]: s["suggest"] for s in manifest["proposed_split"]["sections"]}
    assert headers.get("Changelog") == "history.md"
    assert headers.get("Why") == "ARCHITECTURE.md"
    assert headers.get("Components") == "PROJECT.generated.md"


def test_migrate_blocked_returns_block_status(tmp_path: Path) -> None:
    project = tmp_path
    (project / "PROJECT.md").write_text("# x\n")
    bad_part = {"components": [{"id": "a", "source_files": ["a/x.py"], "intent_mode": "degraded"}]}
    result = migrate_mod.migrate(project, partition_doc=bad_part,
                                 intent_manifest={"summary": {}}, apply=False)
    assert result["status"] == "blocked"
    # nothing archived/migrated on a block
    assert not (project / ".comprehension" / "migration").exists()


def test_migrate_apply_requires_approvals(tmp_path: Path) -> None:
    project = tmp_path
    (project / "PROJECT.md").write_text("# x\n## Components\n")
    result = migrate_mod.migrate(project, partition_doc=_GOOD_PARTITION,
                                 intent_manifest={"summary": {"failed": 0, "gap": 0}},
                                 apply=True, approvals_path=None)
    assert result["status"] == "needs_approvals"
