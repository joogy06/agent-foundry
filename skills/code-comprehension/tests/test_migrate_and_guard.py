def test_is_generated_detects_banner(tmp_path: Path) -> None:
    p = tmp_path / "PROJECT.md"
    p.write_text("<!-- GENERATED by code-comprehension — do not hand-edit -->\n# x\n")
    assert ownership_guard.is_generated(p) is True


def test_is_generated_false_for_hand_doc(tmp_path: Path) -> None:
    p = tmp_path / "PROJECT.md"
    p.write_text("# Hand-written PROJECT.md\n")
    assert ownership_guard.is_generated(p) is False


def test_freshness_digest_extracted(tmp_path: Path) -> None:
    p = tmp_path / "PROJECT.md"
    p.write_text("<!-- FRESHNESS:v1 generated_from=0123456789abcdef -->\n")
    assert ownership_guard.freshness_digest(p) == "0123456789abcdef"


def test_freshness_ok_match_and_mismatch(tmp_path: Path) -> None:
    p = tmp_path / "PROJECT.md"
    p.write_text("<!-- FRESHNESS:v1 generated_from=0123456789abcdef -->\n")
    assert ownership_guard.freshness_ok(p, "0123456789abcdef") is True
    assert ownership_guard.freshness_ok(p, "ffffffffffffffff") is False


def test_lint_fails_on_stale_generated_doc(tmp_path: Path) -> None:
    p = tmp_path / "PROJECT.md"
    p.write_text("<!-- GENERATED by code-comprehension -->\n"
                 "<!-- FRESHNESS:v1 generated_from=aaaaaaaaaaaaaaaa -->\n")
    # expected digest differs → stale/edited → rc 2
    assert ownership_guard.lint_no_manual_edit(p, "bbbbbbbbbbbbbbbb") == 2
    # matching → rc 0
    assert ownership_guard.lint_no_manual_edit(p, "aaaaaaaaaaaaaaaa") == 0


def test_lint_ignores_non_generated_doc(tmp_path: Path) -> None:
    p = tmp_path / "PROJECT.md"
    p.write_text("# Hand-written\n")
    assert ownership_guard.lint_no_manual_edit(p, "anything") == 0


