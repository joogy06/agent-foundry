_GOOD_PARTITION = {
    "components": [
        {"id": "a", "source_files": ["a/x.py"], "intent_mode": "llm"},
        {"id": "b", "source_files": ["b/y.py"], "intent_mode": "llm"},
    ]
}


def test_migrate_blocked_on_failed_component(tmp_path: Path) -> None:
    manifest = {"summary": {"failed": 1, "gap": 0}}
    reason = migrate_mod.migration_blocked_reason(manifest, _GOOD_PARTITION)
    assert reason is not None and "failed" in reason


