GENERATED_BANNER = (
    "<!-- GENERATED by code-comprehension — do not hand-edit; edits are erased on "
    "regen; narrative → ARCHITECTURE.md -->"
)
EDGE_LABEL = "structural (AST/regex; SCIP deferred to v2)"
PROJECT_MD_MAX_LINES = 120
COMPONENT_MD_MAX_LINES = 160

# Fields injected per-run by intent-extract that MUST be stripped for determinism.
_PER_RUN_FIELDS = ("sampled_at", "model_id", "workspace_tree_hash", "content_hash",
                   "extractor_version", "template_hash", "consistency_score")


# ---------------------------------------------------------------------------
# Helpers
# ---------------------------------------------------------------------------


def _sha256_text(text: str) -> str:
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


def _strip_per_run(component: Dict[str, Any]) -> Dict[str, Any]:
    """Drop per-run/run-id fields so the rendered body is stable across cold regens."""
    return {k: v for k, v in component.items() if k not in _PER_RUN_FIELDS}


def _intent_map_for_render(intent_map: Dict[str, Any]) -> Dict[str, Any]:
    """A copy of the intent-map with per-run fields stripped from every component."""
    return {"components": [_strip_per_run(c) for c in intent_map.get("components", [])]}


def _one_line(component: Dict[str, Any]) -> str:
    intent = component.get("intent") or {}
    if isinstance(intent, dict):
        return str(intent.get("one_line", "")).strip() or "(no intent)"
    return "(no intent)"


def _confidence(component: Dict[str, Any]) -> str:
    intent = component.get("intent") or {}
    if isinstance(intent, dict):
        return str(intent.get("confidence_level", "interpretive"))
    return "interpretive"


def _component_source_paths(partition_doc: Dict[str, Any], cid: str) -> List[str]:
    for c in partition_doc.get("components", []):
        if c["id"] == cid:
            return sorted(c.get("source_paths", []))
    return []


def _component_block(partition_doc: Dict[str, Any], cid: str) -> Dict[str, Any]:
    for c in partition_doc.get("components", []):
        if c["id"] == cid:
            return c
    return {}


