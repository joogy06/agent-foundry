_MANIFEST_SKIP_DIRS = {".git", ".venv", "venv", "env", "node_modules", "dist",
                       "build", "site-packages", ".wiring", ".comprehension", ".tox"}


def _find_manifests(project_dir: Path, names: set, max_depth: int = 3) -> List[Path]:
    """Find manifest files by name up to max_depth, pruning vendored dirs.

    The dogfood's manifest lives at app_deploy/requirements.txt (not the repo root),
    so a bounded subdir search is required. Deterministic (sorted).
    """
    found: List[Path] = []
    base_depth = len(project_dir.parts)
    for root, dirs, files in os.walk(project_dir):
        depth = len(Path(root).parts) - base_depth
        if depth >= max_depth:
            dirs[:] = []
        dirs[:] = [d for d in dirs if d not in _MANIFEST_SKIP_DIRS and not d.startswith(".")]
        for f in files:
            if f in names:
                found.append(Path(root) / f)
    return sorted(found)


def parse_external_deps(project_dir: Path) -> List[str]:
    """Parse requirements*.txt / pyproject.toml / package.json for top-level deps.

    Searches the repo root AND bounded subdirs (manifests often live under app_deploy/
    or a service dir, not the root). Deterministic (sorted, de-duplicated). Never raises.
    """
    deps: set = set()
    # requirements*.txt
    for req in _find_manifests(project_dir, {"requirements.txt", "requirements-dev.txt"}):
        for line in req.read_text(encoding="utf-8", errors="replace").splitlines():
            line = line.strip()
            if not line or line.startswith("#") or line.startswith("-"):
                continue
            name = line.split("==")[0].split(">=")[0].split("<")[0].split("~")[0].split("[")[0].split(";")[0].strip()
            if name:
                deps.add(name)
    # package.json
    for pkg in _find_manifests(project_dir, {"package.json"}):
        try:
            data = json.loads(pkg.read_text(encoding="utf-8", errors="replace"))
            for key in ("dependencies", "devDependencies"):
                for name in (data.get(key) or {}):
                    deps.add(name)
        except (json.JSONDecodeError, OSError):
            pass
    # pyproject.toml
    import re
    for pyproject in _find_manifests(project_dir, {"pyproject.toml"}):
        txt = pyproject.read_text(encoding="utf-8", errors="replace")
        for m in re.finditer(r'"([A-Za-z0-9_.\-]+)\s*[=<>~]', txt):
            deps.add(m.group(1))
    return sorted(deps)


def detect_testing(project_dir: Path) -> str:
    """Auto-detect the test command/framework (reused convention). Deterministic."""
    if (project_dir / "pyproject.toml").is_file():
        txt = (project_dir / "pyproject.toml").read_text(errors="replace")
        if "pytest" in txt:
            return "pytest"
    if list(project_dir.glob("tests/test_*.py")) or list(project_dir.glob("test_*.py")):
        return "pytest (tests/ detected)"
    if (project_dir / "package.json").is_file():
        try:
            data = json.loads((project_dir / "package.json").read_text(errors="replace"))
            if "test" in (data.get("scripts") or {}):
                return f"npm test → {data['scripts']['test']}"
        except (json.JSONDecodeError, OSError):
            pass
    return "(no test infrastructure detected)"


# ---------------------------------------------------------------------------
# Edge view → component-level interaction edges
# ---------------------------------------------------------------------------


def _component_edges(edge_view: Dict[str, Any]) -> List[tuple]:
    """Distinct (src_component, dst_component) pairs, sorted. Self-edges dropped."""
    pairs: set = set()
    for e in edge_view.get("edges", []):
        src = e.get("src_component")
        dst = e.get("dst_component")
        if src and dst and src != dst:
            pairs.add((src, dst))
    return sorted(pairs)


# ---------------------------------------------------------------------------
# generated_from (content hashes — NOT wall-clock; C12 working-tree)
# ---------------------------------------------------------------------------


def build_generated_from(
    partition_doc: Dict[str, Any],
    intent_map: Dict[str, Any],
    edge_view: Dict[str, Any],
) -> Dict[str, Any]:
    """Content-hash provenance for the FRESHNESS stamp. Deterministic.

    Hashes the canonical selected source inventory (C5) + intent cache keys +
    edge-view snapshot id + records the working-tree state (C12). model_id is pinned
    (per-component) so a cold regen with a different model is detectable.
    """
    stripped = _intent_map_for_render(intent_map)
    intent_canonical = json.dumps(stripped, sort_keys=True, separators=(",", ":"))
    # model_ids pinned (read from the UN-stripped components, sorted+deduped)
    model_ids = sorted({c.get("model_id", "") for c in intent_map.get("components", []) if c.get("model_id")})
    return {
        "partition_hash": partition_doc.get("partition_hash", ""),
        "intent_map_hash": _sha256_text(intent_canonical),
        # NOT the reconciler's snapshot_id — that carries per-run wall-clock through
        # evidence[].last_seen_at (the wiring extractor's emitted_at). We hash ONLY the
        # deterministic component-edge pairs so the stamp is stable across cold runs.
        "edge_view_id": _deterministic_edge_hash(edge_view),
        "model_ids": model_ids,
        "tree_state": partition_doc.get("tree_state", {}),
        "component_count": len(partition_doc.get("components", [])),
    }


def _deterministic_edge_hash(edge_view: Dict[str, Any]) -> str:
    """Hash the sorted distinct (src_component, dst_component, edge_kind) tuples.

    Excludes all timestamps / evidence / per-run fields so two runs over the same tree
    produce the same digest (the reconciler's snapshot_id does NOT — it embeds
    emitted_at). 16-hex, deterministic."""
    triples = sorted({
        (e.get("src_component", ""), e.get("dst_component", ""), e.get("edge_kind", ""))
        for e in edge_view.get("edges", [])
    })
    canonical = json.dumps(triples, sort_keys=True, separators=(",", ":"))
    return _sha256_text(canonical)[:16]


def freshness_stamp(generated_from: Dict[str, Any]) -> str:
    """The ONLY mutable line in the doc body — keyed to content hashes (no wall-clock)."""
    canonical = json.dumps(generated_from, sort_keys=True, separators=(",", ":"))
    digest = _sha256_text(canonical)[:16]
    return f"<!-- FRESHNESS:v1 generated_from={digest} -->"


