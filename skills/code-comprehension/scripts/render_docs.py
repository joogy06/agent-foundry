#!/usr/bin/env python3
"""render_docs.py — deterministic, ZERO-LLM renderer for code-comprehension.

Pure function `render_all(...) → {PROJECT.md, COMPONENT.md...}`, byte-identical on
re-run GIVEN a fixed intent-map (design §5 + §11 Fix-3/Fix-4 + §12 C10/C12).

Determinism rules:
  - sorted keys / sorted iteration everywhere
  - per-run fields (sampled_at, model_id, run-id, generated_at) are STRIPPED from the
    doc body; the ONLY mutable line is the FRESHNESS stamp, which is keyed to the
    `generated_from` CONTENT hashes (not wall-clock)
  - imports intent-map-render's d1_sequence.render / d4_heatmap.render as PURE
    functions (NOT the CLI, which expects evo .ledger/ paths + HARD-RULE-5 gating)

Edge labeling (§12 C4 — HARD gate #4): every Interaction-Edges section is labeled
"structural (AST/regex)" — SCIP is DEFERRED to v2. Never imply SCIP precision.

Generated-ownership (WP-9): every generated doc carries the GENERATED banner +
`generated_from[]` so a freshness/lint check can detect manual edits.
"""
