def render_project_md(
    project_dir: Path,
    partition_doc: Dict[str, Any],
    intent_map: Dict[str, Any],
    edge_view: Dict[str, Any],
) -> str:
    components = sorted(intent_map.get("components", []), key=lambda c: c.get("component_id", ""))
    comp_by_id = {c.get("component_id"): c for c in components}
    component_ids = sorted(c["id"] for c in partition_doc.get("components", []))

    gen_from = build_generated_from(partition_doc, intent_map, edge_view)
    project_name = project_dir.name

    lines: List[str] = []
    # YAML header
    header = {
        "generated_by": "code-comprehension",
        "generated_from": gen_from,
        "see_also": "ARCHITECTURE.md (hand-owned narrative / why / failure-impact)",
    }
    lines.append("---")
    lines.append(yaml.safe_dump(header, sort_keys=True, default_flow_style=False).rstrip())
    lines.append("---")
    lines.append(GENERATED_BANNER)
    lines.append(freshness_stamp(gen_from))
    lines.append("")
    lines.append(f"# {project_name} — Architecture (generated)")
    lines.append("")
    lines.append("> Generated comprehension front-door. Hand-owned narrative (the *why*, "
                 "external-failure-impact, cross-repo notes) lives in **ARCHITECTURE.md**.")
    lines.append("")

    # Components table
    lines.append("## Components")
    lines.append("")
    lines.append("| Component | Source paths | One-line intent | Confidence |")
    lines.append("|---|---|---|---|")
    for cid in component_ids:
        paths = ", ".join(f"`{p}`" for p in _component_source_paths(partition_doc, cid))
        comp = comp_by_id.get(cid, {})
        lines.append(f"| `{cid}` | {paths} | {_one_line(comp)} | {_confidence(comp)} |")
    lines.append("")

    # Interaction edges (LABELED structural — HARD gate #4)
    lines.append("## Interaction Edges")
    lines.append("")
    lines.append(f"_Edges are **{EDGE_LABEL}** — derived from import/call structure, not a "
                 "symbol-precise index. Every edge below resolves to a `static.jsonl` edge._")
    lines.append("")
    edges = _component_edges(edge_view)
    if edges:
        lines.append("| From | To |")
        lines.append("|---|---|")
        for src, dst in edges:
            lines.append(f"| `{src}` | `{dst}` |")
    else:
        lines.append("_No cross-component structural edges detected._")
    lines.append("")

    # External dependencies
    deps = parse_external_deps(project_dir)
    lines.append("## External Dependencies")
    lines.append("")
    if deps:
        lines.append(", ".join(f"`{d}`" for d in deps))
    else:
        lines.append("_None detected from manifests._")
    lines.append("")

    # Entry points
    lines.append("## Entry Points")
    lines.append("")
    ep_lines: List[str] = []
    for cid in component_ids:
        comp = comp_by_id.get(cid, {})
        for ep in sorted((comp.get("entry_points") or []),
                         key=lambda e: json.dumps(e, sort_keys=True) if isinstance(e, dict) else str(e)):
            if isinstance(ep, dict):
                ep_lines.append(f"- `{cid}`: {ep.get('kind', '?')} {ep.get('detail', '')}".rstrip())
        # partition-level entry-point markers (structural)
        block = _component_block(partition_doc, cid)
        for marker in sorted(block.get("entry_points", [])):
            ep_lines.append(f"- `{cid}`: structural entry-point `{marker}`")
    if ep_lines:
        # dedupe preserving sorted order
        seen = set()
        for ln in ep_lines:
            if ln not in seen:
                lines.append(ln)
                seen.add(ln)
    else:
        lines.append("_No entry points detected._")
    lines.append("")

    # Testing
    lines.append("## Testing")
    lines.append("")
    lines.append(detect_testing(project_dir))
    lines.append("")

    body = "\n".join(lines).rstrip() + "\n"
    return body


# ---------------------------------------------------------------------------
# COMPONENT.md (Level 1)
# ---------------------------------------------------------------------------


def render_component_md(
    project_dir: Path,
    partition_doc: Dict[str, Any],
    component: Dict[str, Any],
    edge_view: Dict[str, Any],
    generated_from: Dict[str, Any],
) -> str:
    cid = component.get("component_id", "unknown")
    block = _component_block(partition_doc, cid)
    single_map = {"components": [_strip_per_run(component)]}

    lines: List[str] = []
    lines.append("---")
    lines.append(yaml.safe_dump({"generated_by": "code-comprehension", "component": cid},
                                sort_keys=True).rstrip())
    lines.append("---")
    lines.append(GENERATED_BANNER)
    lines.append(freshness_stamp(generated_from))
    lines.append("")
    lines.append(f"# {cid} (component)")
    lines.append("")

    # Purpose
    lines.append("## Purpose")
    lines.append("")
    lines.append(_one_line(component))
    intent = component.get("intent") or {}
    if isinstance(intent, dict):
        for r in (intent.get("responsibilities") or []):
            lines.append(f"- {r}")
    lines.append("")
    lines.append(f"_Confidence: **{_confidence(component)}** | intent_mode: "
                 f"**{block.get('intent_mode', 'unknown')}**_")
    lines.append("")

    # Interfaces (structural)
    lines.append("## Interfaces (structural)")
    lines.append("")
    eps = sorted((component.get("entry_points") or []),
                 key=lambda e: json.dumps(e, sort_keys=True) if isinstance(e, dict) else str(e))
    if eps:
        for ep in eps:
            if isinstance(ep, dict):
                lines.append(f"- {ep.get('kind', '?')} — `{ep.get('handler_symbol', ep.get('detail', '?'))}`")
    else:
        lines.append("_No public interface symbols extracted._")
    lines.append("")

    # Internal flow — D1 via the PURE render fn
    lines.append("## Internal Flow")
    lines.append("")
    d1 = d1_sequence.render_single_component(_strip_per_run(component))
    lines.append(d1)
    lines.append("")

    # Key files
    lines.append("## Key Files")
    lines.append("")
    files = sorted(block.get("source_files", []))[:20]
    for f in files:
        lines.append(f"- `{f}`")
    if len(block.get("source_files", [])) > 20:
        lines.append(f"- _… {len(block['source_files']) - 20} more_")
    lines.append("")

    # Edge cases (error paths)
    lines.append("## Edge Cases")
    lines.append("")
    errs = sorted((component.get("error_paths") or []),
                  key=lambda e: json.dumps(e, sort_keys=True) if isinstance(e, dict) else str(e))
    if errs:
        for er in errs:
            if isinstance(er, dict):
                lines.append(f"- {er.get('error_kind', 'raises')} on {er.get('condition', '?')}")
    else:
        lines.append("_No error paths extracted._")
    lines.append("")

    return "\n".join(lines).rstrip() + "\n"


# ---------------------------------------------------------------------------
# Top-level
# ---------------------------------------------------------------------------


def render_all(
    *,
    project_dir: Path,
    out_dir: Path,
    partition_doc: Dict[str, Any],
    intent_map: Dict[str, Any],
    edge_view: Dict[str, Any],
    shadow: bool = True,
) -> Dict[str, Any]:
    """Render the shadow PROJECT.md + per-component COMPONENT.md. Deterministic.

    shadow=True (default) writes to .comprehension/PROJECT.generated.md and
    .comprehension/components/<id>/COMPONENT.md — NEVER the repo's real docs.
    Returns {project_md, component_dir, components: [...]}.
    """
    project_dir = project_dir.resolve()
    out_dir = out_dir.resolve()
    out_dir.mkdir(parents=True, exist_ok=True)

    project_body = render_project_md(project_dir, partition_doc, intent_map, edge_view)
    gen_from = build_generated_from(partition_doc, intent_map, edge_view)

    if shadow:
        project_md_path = out_dir / "PROJECT.generated.md"
        comp_root = out_dir / "components"
    else:
        project_md_path = project_dir / "PROJECT.md"
        comp_root = project_dir / "docs" / "components"

    _atomic_write(project_md_path, project_body)

    comp_root.mkdir(parents=True, exist_ok=True)
    rendered_components: List[str] = []
    for component in sorted(intent_map.get("components", []), key=lambda c: c.get("component_id", "")):
        cid = component.get("component_id", "unknown")
        cdir = comp_root / cid
        cdir.mkdir(parents=True, exist_ok=True)
        body = render_component_md(project_dir, partition_doc, component, edge_view, gen_from)
        _atomic_write(cdir / "COMPONENT.md", body)
        rendered_components.append(cid)

    return {
        "project_md": str(project_md_path),
        "component_dir": str(comp_root),
        "components": rendered_components,
        "generated_from": gen_from,
        "shadow": shadow,
    }


def _atomic_write(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_suffix(path.suffix + f".tmp.{os.getpid()}")
    tmp.write_text(text, encoding="utf-8")
    os.replace(str(tmp), str(path))


# ---------------------------------------------------------------------------
# CLI (for standalone render from a partition + intent-map on disk)
# ---------------------------------------------------------------------------


def main(argv: Optional[List[str]] = None) -> int:
    import argparse
    ap = argparse.ArgumentParser(prog="code-comprehension.render")
    ap.add_argument("--project-dir", required=True)
    ap.add_argument("--partition-doc", required=True, help="synthetic-contract-map.yaml")
    ap.add_argument("--intent-map", required=True, help="merged {components:[...]} yaml/json")
    ap.add_argument("--edge-view", default=None, help="reconciler snapshot json (optional)")
    ap.add_argument("--out-dir", default=None)
    ap.add_argument("--no-shadow", action="store_true")
    ns = ap.parse_args(argv)

    project_dir = Path(ns.project_dir)
    partition_doc = yaml.safe_load(Path(ns.partition_doc).read_text())
    raw = Path(ns.intent_map).read_text()
    try:
        intent_map = json.loads(raw)
    except json.JSONDecodeError:
        intent_map = yaml.safe_load(raw)
    if "components" not in intent_map:
        intent_map = {"components": intent_map if isinstance(intent_map, list) else []}
    edge_view = {}
    if ns.edge_view and Path(ns.edge_view).is_file():
        edge_view = json.loads(Path(ns.edge_view).read_text())
    out_dir = Path(ns.out_dir) if ns.out_dir else (project_dir / ".comprehension")
    result = render_all(project_dir=project_dir, out_dir=out_dir,
                        partition_doc=partition_doc, intent_map=intent_map,
                        edge_view=edge_view, shadow=not ns.no_shadow)
    sys.stdout.write(json.dumps(result, sort_keys=True, indent=2) + "\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
