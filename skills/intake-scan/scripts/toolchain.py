#!/usr/bin/env python3
"""toolchain.py -- the pinned, hash-locked third-party scanner toolchain (#350).

The two third-party scanners are external code, so they are taken in the same way we ask
of anything else: pinned, hash-locked, and never run outside the sandbox.

    skills/intake-scan/toolchain/pins.json            what is pinned
    skills/intake-scan/toolchain/<tool>.lock.txt      every requirement with its hashes

    skills/intake-scan/toolchain/<tool>-build.lock.txt   for a tool built from source: its
                                                      build backend, with hashes

    install   one venv per tool under ~/.foundry/intake-tools/<tool>/venv, built on the
              SYSTEM interpreter with `uv pip install --require-hashes`. A tool pinned by
              commit is then built from that exact commit with --no-deps.
    check     reads the installed metadata and compares it with the pins. It never starts
              a scanner: version from the distribution's METADATA, source revision from
              its direct_url.json, the backend that built it from its WHEEL file, lock
              digests from the install manifest.

`install` never RUNS a scanner: nothing from an installed scanner is imported or executed
here. Running a scanner is `sandbox.py`'s job and happens only inside bwrap.

THE ONE THING THAT DOES RUN AT INSTALL TIME is the build backend of a tool built from
source, on this host and outside the sandbox. So it is locked like everything else: the
backend and what it imports are in the tool's build lock with hashes, they are installed
into the venv by the same --require-hashes command as the dependencies, and the build step
runs with --no-build-isolation (the backend is the one in the venv), --no-index (nothing is
resolved from the index) and --no-cache (a wheel built earlier by some other backend is not
reused). `check` fails when the build lock differs from the pins, lacks the backend, or the
installed wheel was generated by another backend version than the one locked.

A venv is bound into the sandbox at another path, so its console scripts (which carry an
absolute interpreter path) are not used; adapters start `<venv>/bin/python` directly. The
venv interpreter is a link to the system interpreter, which resolves inside the sandbox
because /usr is bound there. That is why the build uses the system interpreter and not a
uv-managed one living under the home directory.

Stdlib only. Importing this module has no side effects.

    toolchain.py install [--root DIR] [--tool NAME] [--json]
    toolchain.py check   [--root DIR] [--tool NAME] [--json]

Exit: 0 every tool present and matching, 1 a tool is missing or mismatched, 3 usage or
internal error.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import os
import re
import shutil
import subprocess
import sys
import tempfile
import time
from typing import Any, Callable, Dict, List, NamedTuple, Optional, Sequence, Tuple

PINS_SCHEMA = "intake-toolchain-pins.v1"
MANIFEST_SCHEMA = "intake-toolchain-install.v1"
MANIFEST_NAME = "install.json"
VENV_NAME = "venv"
TOOLS_ENV = "FOUNDRY_INTAKE_TOOLS"

STATE_OK = "ok"
STATE_MISSING = "missing"
STATE_INCOMPLETE = "incomplete"
STATE_MISMATCH = "mismatch"

SOURCE_INDEX = "index"
SOURCE_GIT = "git"

INSTALL_TIMEOUT_S = 1800

_HERE = os.path.dirname(os.path.abspath(__file__))
TOOLCHAIN_DIR = os.path.join(os.path.dirname(_HERE), "toolchain")
PINS_PATH = os.path.join(TOOLCHAIN_DIR, "pins.json")

_NAME_OK = re.compile(r"^[a-z][a-z0-9_-]{0,39}$")
_COMMIT_OK = re.compile(r"^[0-9a-f]{40}$")
_VERSION_OK = re.compile(r"^[0-9][0-9A-Za-z.+!-]{0,39}$")
_REQUIREMENT = re.compile(r"^([A-Za-z0-9][A-Za-z0-9._-]*)==([^\s;\\]+)")
# Variables the build may see. No token, no key, nothing else of the caller's environment.
_BUILD_ENV_KEYS = ("PATH", "HOME", "TMPDIR", "LANG", "LC_ALL", "SSL_CERT_FILE", "SSL_CERT_DIR",
                   "HTTPS_PROXY", "https_proxy", "NO_PROXY", "no_proxy", "XDG_CACHE_HOME",
                   "SYSTEMROOT", "USERPROFILE", "LOCALAPPDATA", "APPDATA")


class ToolchainError(Exception):
    """The pins or a lock file in the repo are missing or malformed."""


class Pin(NamedTuple):
    tool: str
    distribution: str
    version: str
    source: str                    # "index" or "git"
    url: Optional[str]
    commit: Optional[str]
    lock_name: str
    lock_sha256: str
    build_backend: Optional[str] = None      # set for a tool built from source (a git pin)
    build_lock_name: Optional[str] = None
    build_lock_sha256: Optional[str] = None


class ToolState(NamedTuple):
    tool: str
    state: str                     # ok | missing | incomplete | mismatch
    reasons: Tuple[str, ...]       # fixed words of ours, never tool output
    version_pinned: str
    version_found: Optional[str]
    revision_pinned: Optional[str]
    revision_found: Optional[str]
    venv: str
    python: Optional[str]          # the venv interpreter, when the tool is usable

    def to_dict(self) -> Dict[str, Any]:
        out = dict(self._asdict())
        out["reasons"] = list(self.reasons)
        return out


