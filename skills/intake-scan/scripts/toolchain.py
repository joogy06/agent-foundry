def tool_dir(root: str, tool: str) -> str:
    return os.path.join(root, tool)


def venv_dir(root: str, tool: str) -> str:
    return os.path.join(tool_dir(root, tool), VENV_NAME)


def venv_python(venv: str) -> Optional[str]:
    for rel in (("bin", "python"), ("Scripts", "python.exe")):
        candidate = os.path.join(venv, *rel)
        if os.path.exists(candidate):
            return candidate
    return None


def _site_packages(venv: str) -> List[str]:
    found: List[str] = []
    lib = os.path.join(venv, "lib")
    if os.path.isdir(lib):
        for name in sorted(os.listdir(lib)):
            candidate = os.path.join(lib, name, "site-packages")
            if name.startswith("python") and os.path.isdir(candidate):
                found.append(candidate)
    windows = os.path.join(venv, "Lib", "site-packages")
    if os.path.isdir(windows):
        found.append(windows)
    return found


def _normal(name: str) -> str:
    return re.sub(r"[-_.]+", "-", name).lower()


def _dist_info(venv: str, distribution: str) -> List[str]:
    wanted = _normal(distribution)
    found: List[str] = []
    for site in _site_packages(venv):
        for name in sorted(os.listdir(site)):
            if name.endswith(".dist-info") and _normal(name[:-len(".dist-info")].rsplit("-", 1)[0]) == wanted:
                found.append(os.path.join(site, name))
    return found


def _metadata_version(dist_info: str) -> Optional[str]:
    try:
        with open(os.path.join(dist_info, "METADATA"), "r", encoding="utf-8", errors="replace") as fh:
            for line in fh:
                if not line.strip():
                    break
                if line.lower().startswith("version:"):
                    value = line.split(":", 1)[1].strip()
                    return value if _VERSION_OK.match(value) else None
    except OSError:
        return None
    return None


def _direct_url_commit(dist_info: str) -> Optional[str]:
    try:
        with open(os.path.join(dist_info, "direct_url.json"), "r", encoding="utf-8") as fh:
            data = json.load(fh)
    except (OSError, ValueError):
        return None
    info = data.get("vcs_info") if isinstance(data, dict) else None
    commit = info.get("commit_id") if isinstance(info, dict) else None
    return commit.lower() if isinstance(commit, str) and _COMMIT_OK.match(commit.lower()) else None


def _wheel_generator(dist_info: str) -> Optional[Tuple[str, str]]:
    """(name, version) from the `Generator:` line of an installed distribution's WHEEL file:
    the build backend that produced the wheel. None when there is no such line."""
    try:
        with open(os.path.join(dist_info, "WHEEL"), "r", encoding="utf-8", errors="replace") as fh:
            for line in fh:
                if line.lower().startswith("generator:"):
                    words = line.split(":", 1)[1].split()
                    if len(words) >= 2 and _VERSION_OK.match(words[1]):
                        return _normal(words[0]), words[1]
                    return None
    except OSError:
        return None
    return None


def _read_manifest(root: str, tool: str) -> Optional[Dict[str, Any]]:
    try:
        with open(os.path.join(tool_dir(root, tool), MANIFEST_NAME), "r", encoding="utf-8") as fh:
            data = json.load(fh)
    except (OSError, ValueError):
        return None
    return data if isinstance(data, dict) and data.get("schema") == MANIFEST_SCHEMA else None


def check_tool(pin: Pin, root: Optional[str] = None, toolchain_dir: Optional[str] = None) -> ToolState:
    """The state of one tool. Reads files only; no scanner and no interpreter is started."""
    root = default_root(root)
    venv = venv_dir(root, pin.tool)

    def state(name: str, reasons: Sequence[str], version: Optional[str] = None,
              revision: Optional[str] = None, python: Optional[str] = None) -> ToolState:
        return ToolState(pin.tool, name, tuple(reasons), pin.version, version, pin.commit,
                         revision, venv, python if name == STATE_OK else None)

    python = venv_python(venv)
    if not os.path.isdir(venv) or python is None:
        return state(STATE_MISSING, ["venv-absent"])
    manifest = _read_manifest(root, pin.tool)
    if manifest is None:
        return state(STATE_INCOMPLETE, ["install-manifest-absent"])

    reasons: List[str] = []
    infos = _dist_info(venv, pin.distribution)
    version = _metadata_version(infos[0]) if len(infos) == 1 else None
    revision = _direct_url_commit(infos[0]) if len(infos) == 1 else None
    if len(infos) != 1:
        reasons.append("distribution-absent" if not infos else "distribution-duplicated")
    elif version != pin.version:
        reasons.append("version-mismatch")
    if pin.source == SOURCE_GIT and len(infos) == 1 and revision != pin.commit:
        reasons.append("revision-mismatch")
    try:
        repo_lock = sha256_file(lock_path(pin, toolchain_dir))
    except OSError:
        repo_lock = ""
    if repo_lock != pin.lock_sha256:
        reasons.append("lock-differs-from-pins")
    if manifest.get("lock_sha256") != pin.lock_sha256:
        reasons.append("installed-from-another-lock")
    if pin.build_lock_name:
        # Built from source: the backend that ran at install time must be the locked one.
        try:
            repo_build = sha256_file(build_lock_path(pin, toolchain_dir) or "")
        except OSError:
            repo_build = ""
        if repo_build != pin.build_lock_sha256:
            reasons.append("build-lock-differs-from-pins")
        if manifest.get("build_lock_sha256") != pin.build_lock_sha256:
            reasons.append("installed-from-another-build-lock")
        locked = backend_pin(pin, toolchain_dir)
        if locked is None:
            reasons.append("build-lock-lacks-the-backend")
        elif len(infos) == 1 and _wheel_generator(infos[0]) != (_normal(locked[0]), locked[1]):
            reasons.append("built-by-another-backend")
    if reasons:
        return state(STATE_MISMATCH, reasons, version, revision)
    return state(STATE_OK, [], version, revision, python)


def check(root: Optional[str] = None, tools: Optional[Sequence[str]] = None,
          pins_path: Optional[str] = None, toolchain_dir: Optional[str] = None) -> Dict[str, ToolState]:
    """The state of every pinned tool (or of `tools`), by tool name."""
    pins = load_pins(pins_path)
    names = list(tools) if tools else sorted(pins)
    out: Dict[str, ToolState] = {}
    for name in names:
        if name not in pins:
            raise ToolchainError("no pin for the tool asked for")
        out[name] = check_tool(pins[name], root, toolchain_dir)
    return out


def all_ok(states: Dict[str, ToolState]) -> bool:
    return bool(states) and all(s.state == STATE_OK for s in states.values())


