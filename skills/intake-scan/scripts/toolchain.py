def system_python() -> Optional[str]:
    """The system interpreter the venvs are built on, or None when there is none."""
    if os.name != "posix":
        return None
    for candidate in ("/usr/bin/python3",):
        if os.path.isfile(candidate) and os.access(candidate, os.X_OK):
            return candidate
    return None


def build_env() -> Dict[str, str]:
    return {key: os.environ[key] for key in _BUILD_ENV_KEYS if key in os.environ}


def install_commands(pin: Pin, venv: str, uv: str, python: str,
                     toolchain_dir: Optional[str] = None) -> List[List[str]]:
    """The exact commands that build one tool. Pure: it starts nothing.

    Every package that comes from the index is installed by ONE --require-hashes command,
    the build backend included. The source build then gets no index and no cache: the only
    backend it can run is the hash-locked one already in the venv.
    """
    venv_py = os.path.join(venv, "bin", "python")
    locked = [uv, "pip", "install", "--python", venv_py, "--require-hashes", "--only-binary", ":all:",
              "-r", lock_path(pin, toolchain_dir)]
    build_lock = build_lock_path(pin, toolchain_dir)
    if build_lock is not None:
        locked += ["-r", build_lock]
    commands = [[uv, "venv", "--python", python, "--no-project", venv], locked]
    if pin.source == SOURCE_GIT:
        commands.append([uv, "pip", "install", "--python", venv_py, "--no-cache", "--no-build-isolation",
                         "--no-index", "--no-deps",
                         "%s @ git+%s@%s" % (pin.distribution, pin.url, pin.commit)])
    return commands


Runner = Callable[[List[str], Dict[str, str], int], int]


def _run(argv: List[str], env: Dict[str, str], timeout: int) -> int:
    proc = subprocess.run(argv, stdin=subprocess.DEVNULL, stdout=subprocess.DEVNULL,
                          stderr=subprocess.DEVNULL, env=env, timeout=timeout)
    return proc.returncode


def _write_json(path: str, data: Dict[str, Any]) -> None:
    fd, tmp = tempfile.mkstemp(prefix=".tmp-", dir=os.path.dirname(path))
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as fh:
            json.dump(data, fh, indent=2, sort_keys=True)
            fh.write("\n")
        os.replace(tmp, path)
    except BaseException:
        if os.path.exists(tmp):
            os.unlink(tmp)
        raise


def _is_ours(target: str) -> bool:
    """True when an existing tool directory is one this module made (or is empty).

    `install` removes the old directory before it builds. With a mistyped --root that could
    be somebody else's directory of the same name, so anything that does not look like a
    tool directory is left alone.
    """
    if os.path.islink(target) or not os.path.isdir(target):
        return False
    return set(os.listdir(target)) <= {VENV_NAME, MANIFEST_NAME}


def install_tool(pin: Pin, root: Optional[str] = None, *, uv: Optional[str] = None,
                 python: Optional[str] = None, runner: Optional[Runner] = None,
                 toolchain_dir: Optional[str] = None) -> ToolState:
    """Build one tool's venv from its lock file and return its checked state.

    The old venv is removed first and the install manifest is written last, so an
    interrupted install reads as `incomplete`, never as usable.
    """
    root = default_root(root)
    venv = venv_dir(root, pin.tool)

    def failed(reason: str) -> ToolState:
        return ToolState(pin.tool, STATE_INCOMPLETE if os.path.isdir(venv) else STATE_MISSING,
                         (reason,), pin.version, None, pin.commit, None, venv, None)

    uv = uv or shutil.which("uv")
    python = python or system_python()
    if uv is None:
        return failed("uv-not-found")
    if python is None:
        return failed("system-interpreter-not-found")
    try:
        _pinned, problems = lock_requirements(lock_path(pin, toolchain_dir))
        lock_digest = sha256_file(lock_path(pin, toolchain_dir))
    except OSError:
        return failed("lock-unreadable")
    if problems:
        return failed("lock-not-fully-hashed")
    if lock_digest != pin.lock_sha256:
        return failed("lock-differs-from-pins")
    build_lock = build_lock_path(pin, toolchain_dir)
    build_digest = None
    if pin.source == SOURCE_GIT and build_lock is None:
        return failed("build-lock-not-pinned")
    if build_lock is not None:
        try:
            _pinned, problems = lock_requirements(build_lock)
            build_digest = sha256_file(build_lock)
        except OSError:
            return failed("build-lock-unreadable")
        if problems:
            return failed("build-lock-not-fully-hashed")
        if build_digest != pin.build_lock_sha256:
            return failed("build-lock-differs-from-pins")
        if backend_pin(pin, toolchain_dir) is None:
            return failed("build-lock-lacks-the-backend")

    target = tool_dir(root, pin.tool)
    if os.path.lexists(target) and not _is_ours(target):
        return failed("tool-directory-not-ours")
    try:
        if not os.path.isdir(root):
            os.makedirs(root, 0o700)
        if os.path.isdir(target):
            shutil.rmtree(target)
        os.mkdir(target, 0o700)
    except OSError:
        return failed("tool-directory-unwritable")
    run = runner or _run
    env = build_env()
    for index, argv in enumerate(install_commands(pin, venv, uv, python, toolchain_dir)):
        try:
            status = run(argv, env, INSTALL_TIMEOUT_S)
        except (OSError, subprocess.SubprocessError):
            return failed("install-step-%d-could-not-start" % (index + 1))
        if status != 0:
            return failed("install-step-%d-failed" % (index + 1))
    _write_json(os.path.join(target, MANIFEST_NAME), {
        "schema": MANIFEST_SCHEMA, "tool": pin.tool, "version": pin.version,
        "commit": pin.commit, "lock": pin.lock_name, "lock_sha256": lock_digest,
        "build_lock": pin.build_lock_name, "build_lock_sha256": build_digest,
        "interpreter": python,
        "installed_at": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
    })
    return check_tool(pin, root, toolchain_dir)


def install(root: Optional[str] = None, tools: Optional[Sequence[str]] = None, *,
            uv: Optional[str] = None, python: Optional[str] = None,
            runner: Optional[Runner] = None, pins_path: Optional[str] = None,
            toolchain_dir: Optional[str] = None) -> Dict[str, ToolState]:
    """Build every pinned tool (or `tools`) and return the checked state of each."""
    pins = load_pins(pins_path)
    names = list(tools) if tools else sorted(pins)
    out: Dict[str, ToolState] = {}
    for name in names:
        if name not in pins:
            raise ToolchainError("no pin for the tool asked for")
        out[name] = install_tool(pins[name], root, uv=uv, python=python, runner=runner,
                                 toolchain_dir=toolchain_dir)
    return out


