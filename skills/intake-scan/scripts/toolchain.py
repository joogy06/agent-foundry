def render(states: Dict[str, ToolState]) -> List[str]:
    lines = []
    for name in sorted(states):
        s = states[name]
        line = "%-13s %-10s pinned %s" % (name, s.state, s.version_pinned)
        if s.revision_pinned:
            line += " @ %s" % s.revision_pinned[:7]
        if s.version_found:
            line += "  found %s" % s.version_found
            if s.revision_found:
                line += " @ %s" % s.revision_found[:7]
        if s.reasons:
            line += "  (%s)" % ", ".join(s.reasons)
        lines.append(line)
    return lines


def main(argv: Optional[Sequence[str]] = None) -> int:
    for stream in (sys.stdout, sys.stderr):
        reconfigure = getattr(stream, "reconfigure", None)
        if reconfigure is not None:
            reconfigure(encoding="utf-8", errors="backslashreplace")
    parser = argparse.ArgumentParser(prog="toolchain.py", description="Build or check the pinned scanner toolchain.")
    parser.add_argument("action", choices=("install", "check"))
    parser.add_argument("--root", help="tool root (default: $%s, else ~/.foundry/intake-tools)" % TOOLS_ENV)
    parser.add_argument("--tool", action="append", help="limit to one tool; repeatable")
    parser.add_argument("--json", action="store_true", help="print the states as JSON")
    try:
        args = parser.parse_args(argv)
    except SystemExit as exc:
        return 3 if exc.code not in (0, None) else 0
    try:
        if args.action == "install":
            states = install(args.root, args.tool)
        else:
            states = check(args.root, args.tool)
    except ToolchainError as exc:
        print("toolchain: %s" % exc, file=sys.stderr)
        return 3
    if args.json:
        print(json.dumps({"root": default_root(args.root),
                          "tools": {k: v.to_dict() for k, v in states.items()}}, indent=2, sort_keys=True))
    else:
        print("root: %s" % default_root(args.root))
        for line in render(states):
            print(line)
    return 0 if all_ok(states) else 1


if __name__ == "__main__":
    sys.exit(main())
