def default_root(override: Optional[str] = None) -> str:
    """Where the tools live: the argument, else $FOUNDRY_INTAKE_TOOLS, else the home tree."""
    if override:
        return os.path.abspath(override)
    env = os.environ.get(TOOLS_ENV)
    if env:
        return os.path.abspath(env)
    return os.path.join(os.path.expanduser("~"), ".foundry", "intake-tools")


def sha256_file(path: str) -> str:
    digest = hashlib.sha256()
    with open(path, "rb") as fh:
        for chunk in iter(lambda: fh.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def load_pins(pins_path: Optional[str] = None) -> Dict[str, Pin]:
    """Read and validate pins.json. Raises ToolchainError on anything unexpected."""
    path = pins_path or PINS_PATH
    try:
        with open(path, "r", encoding="utf-8") as fh:
            raw = json.load(fh)
    except (OSError, ValueError) as exc:
        raise ToolchainError("pins unreadable (%s)" % type(exc).__name__)
    if not isinstance(raw, dict) or raw.get("schema") != PINS_SCHEMA or not isinstance(raw.get("tools"), dict):
        raise ToolchainError("pins have an unknown schema")
    pins: Dict[str, Pin] = {}
    for tool, row in raw["tools"].items():
        if not isinstance(row, dict) or not _NAME_OK.match(str(tool)):
            raise ToolchainError("pins hold a malformed tool entry")
        source = row.get("source") or {}
        kind = source.get("type")
        version = str(row.get("version", ""))
        lock_name = str(row.get("lock", ""))
        digest = str(row.get("lock_sha256", ""))
        if kind not in (SOURCE_INDEX, SOURCE_GIT) or not _VERSION_OK.match(version):
            raise ToolchainError("pins hold a malformed source or version")
        if os.path.basename(lock_name) != lock_name or not lock_name.endswith(".lock.txt"):
            raise ToolchainError("pins name a lock file outside the toolchain directory")
        if not re.match(r"^[0-9a-f]{64}$", digest):
            raise ToolchainError("pins hold a malformed lock digest")
        url = commit = backend = build_name = build_digest = None
        if kind == SOURCE_GIT:
            url, commit = str(source.get("url", "")), str(source.get("commit", ""))
            if not url.startswith("https://") or not _COMMIT_OK.match(commit):
                raise ToolchainError("a commit pin needs an https URL and a full commit id")
            build = row.get("build")
            if not isinstance(build, dict):
                raise ToolchainError("a commit pin is built from source and needs a build lock")
            backend, build_name = str(build.get("backend", "")), str(build.get("lock", ""))
            build_digest = str(build.get("lock_sha256", ""))
            if not _NAME_OK.match(backend):
                raise ToolchainError("pins hold a malformed build backend name")
            if (os.path.basename(build_name) != build_name or not build_name.endswith(".lock.txt")
                    or build_name == lock_name):
                raise ToolchainError("pins name a build lock file outside the toolchain directory")
            if not re.match(r"^[0-9a-f]{64}$", build_digest):
                raise ToolchainError("pins hold a malformed build lock digest")
        pins[str(tool)] = Pin(str(tool), str(row.get("distribution") or tool), version, kind,
                              url, commit, lock_name, digest, backend, build_name, build_digest)
    if not pins:
        raise ToolchainError("pins name no tool")
    return pins


def lock_path(pin: Pin, toolchain_dir: Optional[str] = None) -> str:
    return os.path.join(toolchain_dir or TOOLCHAIN_DIR, pin.lock_name)


def build_lock_path(pin: Pin, toolchain_dir: Optional[str] = None) -> Optional[str]:
    if not pin.build_lock_name:
        return None
    return os.path.join(toolchain_dir or TOOLCHAIN_DIR, pin.build_lock_name)


def backend_pin(pin: Pin, toolchain_dir: Optional[str] = None) -> Optional[Tuple[str, str]]:
    """(backend name, version) as the build lock pins it; None when the tool has no build
    lock, the lock is unreadable or not fully hashed, or the backend is not in it."""
    path = build_lock_path(pin, toolchain_dir)
    if path is None or not pin.build_backend:
        return None
    try:
        pinned, problems = lock_requirements(path)
    except (OSError, ValueError):
        return None
    if problems:
        return None
    for name, version in pinned:
        if _normal(name) == _normal(pin.build_backend):
            return pin.build_backend, version
    return None


def lock_requirements(path: str) -> Tuple[List[Tuple[str, str]], List[str]]:
    """(pinned requirements, problems) of a lock file.

    Every requirement must be `name==version` and carry at least one --hash. Anything else
    (a bare name, a URL, an index option) is a problem: the lock would not be fully locked.
    """
    with open(path, "r", encoding="utf-8") as fh:
        text = fh.read()
    logical: List[str] = []
    buffer = ""
    for raw in text.splitlines():
        line = raw.strip()
        if not buffer and (not line or line.startswith("#")):
            continue
        if line.endswith("\\"):
            buffer += line[:-1] + " "
            continue
        logical.append((buffer + line).strip())
        buffer = ""
    if buffer.strip():
        logical.append(buffer.strip())
    pinned: List[Tuple[str, str]] = []
    problems: List[str] = []
    for entry in logical:
        match = _REQUIREMENT.match(entry)
        if match is None:
            problems.append("not-pinned")
            continue
        if "--hash=sha256:" not in entry:
            problems.append("no-hash")
            continue
        pinned.append((match.group(1).lower(), match.group(2)))
    return pinned, problems


