#!/usr/bin/env python3
"""radar.py -- the tool-radar library: build the index, lint entries, list stale ones, search.

    radar.py [--root DIR] index                  rewrite INDEX.md and the SKILL.md entry list
    radar.py [--root DIR] lint                   check every entry; exit 1 on any error
    radar.py [--root DIR] stale [--days N] [--today YYYY-MM-DD]
                                                 entries past review_by (or due within N days)
    radar.py [--root DIR] find TEXT [--ring R] [--category C]
                                                 search name, slug, category, alternative_to, tags

The default root is the skill directory this file sits in. Each entry is
`entries/<slug>.md`: one fenced ```radar block of `key: value` lines, then markdown sections.
List values are written `[a, b, c]`. Stdlib only; no YAML parser, on purpose.

Exit codes: 0 ok (find: at least one match; stale: nothing stale), 1 findings (lint errors,
invalid entries, stale entries, no match), 2 usage error or unreadable library.
"""
from __future__ import annotations

import argparse
import datetime as dt
import re
import sys
from pathlib import Path
from urllib.parse import urlsplit

SKILL_DIR = Path(__file__).resolve().parent.parent

CATEGORIES = (
    "coding-agent", "llm-model", "llm-serving", "seo-data", "voice-audio", "image-editing",
    "image-generation", "video", "automation", "observability", "data", "security",
    "dev-tool", "dev-methodology", "git-tooling", "other",
)
RINGS = ("adopt", "trial", "assess", "hold")
MCP_VALUES = ("server", "client", "both", "none", "unknown")
REQUIRED = (
    "name", "slug", "category", "alternative_to", "homepage", "repo", "licence_code",
    "licence_other", "cost", "maturity", "mcp", "ring", "reviewed", "review_by",
    "suggested_by", "related_skills", "tags", "verdict",
)
OPTIONAL = ("origin",)
LIST_FIELDS = ("related_skills", "tags")
SECTIONS = (
    "What it is", "Verified facts", "Claims that are false or overstated", "Foundry fit",
    "Decision and next step", "Sources",
)
DEFAULT_REVIEW_DAYS = 90
#: Each ring above assess must name its evidence in "Decision and next step".
RING_EVIDENCE = {
    "hold": (r"^\W*(hold because|reason:)\s*\S.{9,}", "'Hold because ...' or 'Reason: ...'"),
    "trial": (r"^\W*success:\s*\S.{9,}", "a 'Success: ...' line naming what the trial must show"),
    "adopt": (r"^\W*approved by\b.{5,}", "an 'Approved by ...' line (owner and date)"),
}
FACT_TAG = re.compile(r"^[-*]\s+(VERIFIED|LIKELY|UNCERTAIN)\b")
URL_TOKEN = re.compile(r"https?://[^\s<>`\"']+")
SLUG = re.compile(r"^[a-z0-9]+(?:-[a-z0-9]+)*$")
ISO_DATE = re.compile(r"^\d{4}-\d{2}-\d{2}$")
DATE_IN_TEXT = re.compile(r"\b\d{4}-\d{2}(?:-\d{2})?\b")
FENCE = re.compile(r"^(```|~~~)")
COMMENT = re.compile(r"<!--.*?-->", re.S)
OPEN_BLOCK = re.compile(r"^```radar[ \t]*$", re.M)
LIST_START = "<!-- radar:entries:start (generated by scripts/radar.py index; do not edit) -->"
LIST_END = "<!-- radar:entries:end -->"
INDEX_HEADER = (
    "# Tool radar index\n\n"
    "Generated by `scripts/radar.py index` from `entries/*.md`. Do not edit by hand.\n\n"
    "Rings: adopt = in use or approved; trial = try on a real task; assess = worth knowing, "
    "no use yet; hold = do not use (see the entry for why).\n\n"
)
INDEX_COLUMNS = ("Tool", "Category", "Alternative to", "Ring", "Licence", "Reviewed",
                 "Review by", "Verdict")


class Entry:
    def __init__(self, path: Path, meta: dict, body: str, errors: list[str]):
        self.path = path
        self.meta = meta
        self.body = body
        self.errors = errors

    def get(self, key: str, default=""):
        return self.meta.get(key, default)


def is_url(value: str) -> bool:
    parts = urlsplit(value)
    return parts.scheme in ("http", "https") and bool(parts.hostname) and " " not in value


def _parse_value(key: str, raw: str):
    raw = raw.strip()
    if key in LIST_FIELDS:
        if not (raw.startswith("[") and raw.endswith("]")):
            raise ValueError(f"{key} must be a list written [a, b]")
        inner = raw[1:-1].strip()
        if not inner:
            return []
        items = [item.strip() for item in inner.split(",")]
        if any(not item for item in items):
            raise ValueError(f"{key} has an empty list element")
        return items
    return raw


def parse_entry(path: Path) -> Entry:
    errors: list[str] = []
    try:
        text = path.read_text(encoding="utf-8-sig").replace("\r\n", "\n")
    except (OSError, UnicodeDecodeError) as exc:
        return Entry(path, {}, "", [f"unreadable: {exc}"])
    opens = list(OPEN_BLOCK.finditer(text))
    if not opens:
        return Entry(path, {}, text, ["no ```radar metadata block"])
    if len(opens) > 1:
        errors.append("more than one ```radar block")
    start = opens[0]
    close = re.compile(r"^```[ \t]*$", re.M).search(text, start.end())
    if close is None:
        return Entry(path, {}, text, errors + ["the ```radar block is never closed"])
    if text[:start.start()].strip():
        errors.append("the ```radar block must be the first thing in the file")
    meta: dict = {}
    for n, line in enumerate(text[start.end():close.start()].splitlines(), 1):
        if not line.strip() or line.lstrip().startswith("#"):
            continue
        key, sep, raw = line.partition(":")
        key = key.strip()
        if not sep or not re.fullmatch(r"[a-z_]+", key):
            errors.append(f"metadata line {n} is not `key: value`: {line.strip()!r}")
            continue
        if key in meta:
            errors.append(f"duplicate key {key!r}")
            continue
        if key not in REQUIRED and key not in OPTIONAL:
            errors.append(f"unknown key {key!r}")
            continue
        try:
            meta[key] = _parse_value(key, raw)
        except ValueError as exc:
            errors.append(str(exc))
    if not meta:
        errors.append("the ```radar block holds no fields")
    return Entry(path, meta, text[close.end():], errors)


def _date(value) -> dt.date | None:
    if not ISO_DATE.match(str(value)):
        return None
    try:
        return dt.date.fromisoformat(str(value))
    except ValueError:
        return None


def _strip_code(body: str) -> str:
    """Drop fenced code blocks and HTML comments so they cannot hold sections or sources."""
    out, in_fence = [], False
    for line in COMMENT.sub("", body).splitlines():
        if FENCE.match(line.strip()):
            in_fence = not in_fence
            continue
        if not in_fence:
            out.append(line)
    return "\n".join(out)


def sections(body: str) -> tuple[dict[str, str], list[str]]:
    """Return ({heading: text}, [duplicate headings]) for the level-2 headings in body."""
    out: dict[str, str] = {}
    dupes: list[str] = []
    parts = re.split(r"^## +(.+?)\s*$", _strip_code(body), flags=re.M)
    for i in range(1, len(parts) - 1, 2):
        name = parts[i].strip()
        if name in out:
            dupes.append(name)
        out[name] = parts[i + 1]
    return out, dupes


def check_facts(text: str) -> list[str]:
    errors = []
    bullets = [ln.strip() for ln in text.splitlines() if re.match(r"^\s*[-*]\s", ln)]
    if not bullets:
        return ["Verified facts has no bullet facts"]
    for bullet in bullets:
        tag = FACT_TAG.match(bullet)
        if not tag:
            errors.append(f"fact without a VERIFIED/LIKELY/UNCERTAIN tag: {bullet[:60]!r}")
        elif tag.group(1) != "UNCERTAIN" and not re.search(r"\bsources?:", bullet, re.I):
            errors.append(f"{tag.group(1)} fact without 'Source:': {bullet[:60]!r}")
    return errors


def check_entry(entry: Entry, skills_root: Path | None = None,
                today: dt.date | None = None) -> tuple[list[str], list[str]]:
    """Return (errors, warnings) for one parsed entry."""
    errors = list(entry.errors)
    warnings: list[str] = []
    meta = entry.meta
    today = today or dt.date.today()
    for key in REQUIRED:
        value = meta.get(key)
        if value is None:
            errors.append(f"missing field {key!r}")
        elif key not in LIST_FIELDS and not str(value).strip():
            errors.append(f"empty field {key!r}")
    slug = meta.get("slug", "")
    if slug and not SLUG.match(slug):
        errors.append(f"slug {slug!r} is not lowercase-hyphenated")
    if slug and entry.path.stem != slug:
        errors.append(f"file name {entry.path.name!r} does not match slug {slug!r}")
    for key, allowed in (("category", CATEGORIES), ("ring", RINGS), ("mcp", MCP_VALUES)):
        if key in meta and meta[key] not in allowed:
            errors.append(f"{key} {meta[key]!r} not in {', '.join(allowed)}")
    reviewed, review_by = _date(meta.get("reviewed", "")), _date(meta.get("review_by", ""))
    if "reviewed" in meta and reviewed is None:
        errors.append(f"reviewed {meta['reviewed']!r} is not YYYY-MM-DD")
    if "review_by" in meta and review_by is None:
        errors.append(f"review_by {meta['review_by']!r} is not YYYY-MM-DD")
    if reviewed and reviewed > today:
        errors.append(f"reviewed {reviewed} is in the future")
    if reviewed and review_by:
        gap = (review_by - reviewed).days
        if gap <= 0:
            errors.append("review_by must be after reviewed")
        elif gap > DEFAULT_REVIEW_DAYS:
            errors.append(f"review_by is {gap} days after reviewed; the limit is "
                          f"{DEFAULT_REVIEW_DAYS} (shorter is fine)")
    for key in ("homepage", "repo"):
        value = str(meta.get(key, ""))
        if value and value != "n/a" and not is_url(value):
            errors.append(f"{key} must be an http(s) URL with a host, or n/a")
    if "maturity" in meta and not DATE_IN_TEXT.search(str(meta["maturity"])):
        warnings.append("maturity carries no date (YYYY-MM or YYYY-MM-DD)")
    if "tags" in meta and not meta["tags"]:
        warnings.append("no tags: find will only match on name and category")
    found, dupes = sections(entry.body)
    for name in dupes:
        errors.append(f"section '## {name}' appears twice")
    for name in SECTIONS:
        if name not in found:
            errors.append(f"missing section '## {name}'")
        elif not found[name].strip():
            errors.append(f"section '## {name}' is empty")
    if found.get("Verified facts", "").strip():
        errors.extend(check_facts(found["Verified facts"]))
    if "Sources" in found and not any(is_url(u.rstrip(".,;:)")) for u in
                                      URL_TOKEN.findall(found["Sources"])):
        errors.append("Sources lists no URL")
    rule = RING_EVIDENCE.get(meta.get("ring", ""))
    if rule and not re.search(rule[0], found.get("Decision and next step", ""), re.I | re.M):
        errors.append(f"ring {meta['ring']} needs {rule[1]} in 'Decision and next step'")
    if skills_root is not None:
        for skill in meta.get("related_skills", []):
            if not (skills_root / skill / "SKILL.md").is_file():
                warnings.append(f"related skill {skill!r} not found under {skills_root}")
    return errors, warnings


def load(root: Path) -> list[Entry]:
    entries_dir = root / "entries"
    if not entries_dir.is_dir():
        raise FileNotFoundError(f"no entries/ directory under {root}")
    return [parse_entry(p) for p in sorted(entries_dir.glob("*.md"))]


def _cell(value) -> str:
    if isinstance(value, list):
        value = ", ".join(value)
    return str(value).replace("|", "\\|").replace("\n", " ").strip()


def render_index(entries: list[Entry]) -> str:
    rows = sorted(entries, key=lambda e: (e.get("category"), str(e.get("name")).lower(),
                                          e.path.name))
    lines = ["| " + " | ".join(INDEX_COLUMNS) + " |",
             "|" + "---|" * len(INDEX_COLUMNS)]
    for e in rows:
        licence = e.get("licence_code")
        other = str(e.get("licence_other"))
        if other and not other.startswith("n/a"):
            licence = f"{licence}; {other}"
        name = f"[{_cell(e.get('name'))}](entries/{e.path.name})"
        cells = [name] + [_cell(v) for v in (
            e.get("category"), e.get("alternative_to"), e.get("ring"), licence,
            e.get("reviewed"), e.get("review_by"), e.get("verdict"))]
        lines.append("| " + " | ".join(cells) + " |")
    return INDEX_HEADER + "\n".join(lines) + "\n"


def render_entry_list(entries: list[Entry]) -> str:
    paths = " · ".join(f"`entries/{e.path.name}`" for e in entries)
    return f"{LIST_START}\n{paths}\n{LIST_END}"


def splice_entry_list(skill_md: str, block: str) -> str | None:
    start, end = skill_md.find(LIST_START), skill_md.find(LIST_END)
    if start < 0 or end < start:
        return None
    return skill_md[:start] + block + skill_md[end + len(LIST_END):]


def _read(path: Path) -> str:
    return path.read_text(encoding="utf-8-sig").replace("\r\n", "\n")


def _write(path: Path, text: str) -> None:
    tmp = path.with_suffix(path.suffix + ".tmp")
    tmp.write_text(text, encoding="utf-8", newline="\n")
    tmp.replace(path)


def _report_invalid(entries: list[Entry]) -> list[Entry]:
    bad = [e for e in entries if e.errors]
    for e in bad:
        print(f"invalid entry {e.path.name}: {'; '.join(e.errors)}", file=sys.stderr)
    return bad


def cmd_index(root: Path) -> int:
    entries = load(root)
    if _report_invalid(entries):
        print("index not written: fix the invalid entries first (run: radar.py lint)",
              file=sys.stderr)
        return 1
    _write(root / "INDEX.md", render_index(entries))
    skill_md = root / "SKILL.md"
    if skill_md.is_file():
        spliced = splice_entry_list(_read(skill_md), render_entry_list(entries))
        if spliced is None:
            print(f"warning: no entry-list markers in {skill_md}", file=sys.stderr)
        else:
            _write(skill_md, spliced)
    print(f"indexed {len(entries)} entries -> {root / 'INDEX.md'}")
    return 0


def cmd_lint(root: Path, today: dt.date) -> int:
    entries = load(root)
    skills_root = root.parent if (root.parent / "research-for-skills").is_dir() else None
    n_err = 0
    slugs: dict[str, Path] = {}
    for entry in entries:
        errors, warnings = check_entry(entry, skills_root, today)
        slug = entry.get("slug")
        if slug and slug in slugs:
            errors.append(f"slug {slug!r} also used by {slugs[slug].name}")
        slugs.setdefault(slug, entry.path)
        for msg in errors:
            print(f"ERROR {entry.path.name}: {msg}")
        for msg in warnings:
            print(f"warn  {entry.path.name}: {msg}")
        n_err += len(errors)
    index = root / "INDEX.md"
    if not index.is_file() or _read(index) != render_index(entries):
        print("ERROR INDEX.md: out of sync with entries/ (run: radar.py index)")
        n_err += 1
    skill_md = root / "SKILL.md"
    if skill_md.is_file():
        text = _read(skill_md)
        if splice_entry_list(text, render_entry_list(entries)) != text:
            print("ERROR SKILL.md: entry list out of sync with entries/ (run: radar.py index)")
            n_err += 1
    print(f"{len(entries)} entries, {n_err} errors")
    return 1 if n_err else 0


def cmd_stale(root: Path, days: int, today: dt.date) -> int:
    try:
        horizon = today + dt.timedelta(days=days)
    except OverflowError:
        horizon = dt.date.max
    hits = []
    for entry in load(root):
        due = _date(entry.get("review_by"))
        if due is None:
            hits.append((dt.date.min, entry, "review_by unreadable"))
        elif due <= horizon:
            label = "OVERDUE" if due < today else "due"
            hits.append((due, entry, f"{label} {due.isoformat()}"))
    for _, entry, why in sorted(hits, key=lambda h: (h[0], h[1].path.name)):
        print(f"{entry.get('slug') or entry.path.stem}\t{entry.get('ring')}\t{why}\t"
              f"reviewed {entry.get('reviewed')}")
    if not hits:
        print("nothing stale")
    return 1 if hits else 0


def cmd_find(root: Path, text: str, ring: str | None, category: str | None) -> int:
    needle = text.lower()
    entries = load(root)
    invalid = _report_invalid(entries)
    hits = 0
    for entry in entries:
        if ring and entry.get("ring") != ring:
            continue
        if category and entry.get("category") != category:
            continue
        hay = " ".join(" ".join(v) if isinstance(v, list) else str(v) for v in (
            entry.get(k) for k in ("name", "slug", "category", "alternative_to", "tags")))
        if needle in (hay + " " + entry.path.stem).lower():
            hits += 1
            print(f"{entry.get('name') or entry.path.stem}\t{entry.get('category')}\t"
                  f"{entry.get('ring')}\tentries/{entry.path.name}\t{entry.get('verdict')}")
    if not hits:
        print(f"no entry matches {text!r}; check INDEX.md, then consider an intake")
        if invalid:
            print(f"note: {len(invalid)} invalid entries could not be searched fully "
                  "(see stderr)")
    return 0 if hits else 1


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="radar.py", description=__doc__.split("\n\n")[0])
    parser.add_argument("--root", type=Path, default=SKILL_DIR,
                        help="skill directory holding entries/ (default: this skill); "
                             "goes before the command")
    sub = parser.add_subparsers(dest="cmd", required=True)
    sub.add_parser("index", help="rewrite INDEX.md and the SKILL.md entry list")
    p_lint = sub.add_parser("lint", help="check entries, enums, dates, sources, index sync")
    p_lint.add_argument("--today", help="override today's date (YYYY-MM-DD)")
    p_stale = sub.add_parser("stale", help="entries past review_by")
    p_stale.add_argument("--days", type=int, default=0,
                         help="also list entries falling due within N days")
    p_stale.add_argument("--today", help="override today's date (YYYY-MM-DD)")
    p_find = sub.add_parser("find", help="search name, slug, category, alternative_to, tags")
    p_find.add_argument("text")
    p_find.add_argument("--ring", choices=RINGS)
    p_find.add_argument("--category", choices=CATEGORIES)
    args = parser.parse_args(argv)
    root = args.root.resolve()
    today = dt.date.today()
    if getattr(args, "today", None):
        today = _date(args.today)
        if today is None:
            parser.error("--today must be YYYY-MM-DD")
    try:
        if args.cmd == "index":
            return cmd_index(root)
        if args.cmd == "lint":
            return cmd_lint(root, today)
        if args.cmd == "stale":
            if args.days < 0:
                parser.error("--days must be >= 0")
            return cmd_stale(root, args.days, today)
        return cmd_find(root, args.text, args.ring, args.category)
    except (OSError, UnicodeDecodeError) as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 2


def _harden_streams() -> None:
    """Fallback when _meta/portable_cli.py is absent: keep a cp1252 console from crashing."""
    for stream in (sys.stdout, sys.stderr):
        try:
            stream.reconfigure(encoding="utf-8", errors="backslashreplace")
        except (AttributeError, ValueError):
            pass


if __name__ == "__main__":
    sys.path.insert(0, str(Path(__file__).resolve().parents[2] / "_meta"))
    try:
        from portable_cli import run_cli  # #251 stream hardening
    except ImportError:                   # installed without _meta: harden locally
        _harden_streams()
        sys.exit(main())
    sys.exit(run_cli(main))
